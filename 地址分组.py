import random


def split_list_into_groups(data: dict, num_groups: int) -> list:
    """
    将列表按平均数量分成指定的组数

    Args:
        data: 要分组的列表
        num_groups: 要分成的组数

    Returns:
        分组后的二维列表
    """
    data = data["Data"]["data"]
    data = [item["ip_addr"] for item in data if item.get("ip_addr")]
    random.shuffle(data)
    if not data:
        return []

    if num_groups <= 0:
        raise ValueError("组数必须大于0")

    if num_groups > len(data):
        raise ValueError("组数不能大于列表长度")

    # 计算每组的基本数量和余数
    total_length = len(data)
    base_size = total_length // num_groups
    remainder = total_length % num_groups

    groups = []
    start_index = 0

    for i in range(num_groups):
        # 前remainder组多分配一个元素，确保均匀分配
        current_size = base_size + (1 if i < remainder else 0)
        end_index = start_index + current_size
        groups.append(data[start_index:end_index])
        start_index = end_index

    return groups


